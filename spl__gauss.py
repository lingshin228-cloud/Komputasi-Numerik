# SEL 1: Import Library dan Inisialisasi Fungsi
import numpy as np

def eliminasi_gauss(A, b):
    n = len(b)
    # Menggabungkan A dan b menjadi Matriks Augmented [A|b]
    M = np.hstack([A, b.reshape(-1, 1)])
    print("=== Matriks Augmented Awal ===")
    print(M)
    print("\n-----------------------------------\n")
    return M, n

"""Sel ini berfungsi untuk memasukkan (import) library numpy ke dalam Google Colab. Library ini sangat penting dan wajib ada karena menyediakan fungsi-fungsi untuk mengolah matriks dan array dengan mudah, yang akan kita gunakan dalam perhitungan Eliminasi Gauss"""

# SEL 2: Proses Eliminasi Maju (Merubah ke Matriks Segitiga Atas)
def eliminasi_maju(M, n):
    for i in range(n):
        pivot = M[i, i]
        if pivot == 0:
            raise ValueError(f"Pivot pada baris ke-{i+1} bernilai 0. Diperlukan pivoting parsial.")

        for j in range(i + 1, n):
            factor = M[j, i] / pivot
            M[j, i:] = M[j, i:] - factor * M[i, i:]

    print("=== Matriks Setelah Eliminasi Maju (Segitiga Atas) ===")
    print(np.round(M, 4))
    print("\n-----------------------------------\n")
    return M

"""Sel ini digunakan untuk mendefinisikan Sistem Persamaan Linear (SPL) ke dalam bentuk Matriks Augmented (penggabungan antara matriks koefisien variabel dan matriks konstanta hasil di sebelah kanan). Tipe data diatur sebagai float agar hasil pembagian pecahan atau desimal tidak dibulatkan menjadi angka nol secara otomatis oleh Python"""

# SEL 3: Proses Substitusi Mundur
def substitusi_mundur(M, n):
    x = np.zeros(n)
    for i in range(n - 1, -1, -1):
        x[i] = (M[i, -1] - np.dot(M[i, i+1:n], x[i+1:n])) / M[i, i]
    return x

"""Sel ini adalah inti dari algoritma Eliminasi Gauss. Tujuannya adalah melakukan Operasi Baris Elementer (OBE) secara otomatis untuk mengubah bagian bawah diagonal matriks menjadi angka 0 (membentuk matriks segitiga atas). Proses ini mencakup normalisasi nilai pivot (agar bernilai 1) dan pengurangan baris di bawahnya"""

# SEL 4: Input Data dan Menjalankan Program

# 1. Definisi Matriks Koefisien (A) dan Vektor Konstanta (b)
A = np.array([
    [2.0,  1.0, -1.0],
    [-3.0, -1.0,  2.0],
    [-2.0,  1.0,  2.0]
], dtype=float)

b = np.array([8.0, -11.0, -3.0], dtype=float)

# 2. Jalankan Langkah-Langkah
M, n = eliminasi_gauss(A, b)
M_segitiga = eliminasi_maju(M, n)
solusi = substitusi_mundur(M_segitiga, n)

# 3. Tampilkan Hasil Akhir
print("=== Hasil Solusi Variabel ===")
for i in range(n):
    print(f"x{i+1} = {solusi[i]:.2f}")

"""Setelah matriks berhasil diubah menjadi bentuk segitiga atas pada sel sebelumnya, sel ini bertugas melakukan substitusi mundur (back-substitution). Komputer akan mulai menghitung nilai variabel terakhir, kemudian naik ke atas secara berurutan untuk menemukan nilai semua variabel (misalnya $x, y,$ dan $z$) secara akurat"""